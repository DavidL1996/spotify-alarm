// Config plugin for the local AlarmKit module (iOS only).
//
// 1. Adds NSAlarmKitUsageDescription to Info.plist. Without it (or with an empty string)
//    "apps can't schedule alarms with AlarmKit":
//    https://developer.apple.com/documentation/alarmkit/scheduling-an-alarm-with-alarmkit
//    AlarmKit needs no entitlement.
// 2. Generates SpotifyAlarmOpenIntent.swift into the *app target*: the App Intent that AlarmKit
//    runs when the alarm's "Open" button is tapped. It lives in the app target (not the pod)
//    so Xcode's App Intents metadata extraction definitely sees it. See ios/AlarmOpenHandoff.swift.
//
// No widget extension: we schedule alert-only alarms (no countdown), and Apple only requires a
// widget extension "if an app supports a countdown presentation".
const { IOSConfig, withInfoPlist } = require('expo/config-plugins');

const DEFAULT_USAGE =
  'Spotify Alarm uses alarms so your wake-up alarms ring even in silent mode or Focus.';

// Must match AlarmOpenHandoff.providerClassName in ios/AlarmOpenHandoff.swift.
const PROVIDER_CLASS_NAME = 'SpotifyAlarmOpenIntentProvider';

const intentSource = `// Generated by modules/alarm-kit/app.plugin.js during prebuild. Do not edit.
import AppIntents
import Foundation
// Explicitly "internal": Expo's generated ExpoModulesProvider.swift in the same app target uses
// \`internal import AlarmKitBridge\`, and Swift rejects mixing that with a plain (implicit) import
// ("ambiguous implicit access level for import"). Nothing in this file is public, so internal is enough.
internal import AlarmKitBridge

// Runs in the app when the user taps "Open" on an AlarmKit alarm
// (AlarmPresentation.Alert secondaryButtonBehavior .custom -> AlarmConfiguration secondaryIntent).
// Shape follows Apple's AlarmKit sample (WWDC25 "Wake up to the AlarmKit API"), using
// supportedModes instead of openAppWhenRun, which is deprecated in iOS 26:
// https://developer.apple.com/documentation/appintents/appintent/supportedmodes
@available(iOS 26.0, *)
struct OpenSpotifyAlarmIntent: LiveActivityIntent {
  static let title: LocalizedStringResource = "Open Spotify Alarm"
  static let supportedModes: IntentModes = .foreground(.immediate)
  static let isDiscoverable: Bool = false

  @Parameter(title: "Alarm ID")
  var alarmId: String

  @Parameter(title: "Playlist ID")
  var playlistId: String?

  init() {
    self.alarmId = ""
    self.playlistId = nil
  }

  init(alarmId: String, playlistId: String?) {
    self.alarmId = alarmId
    self.playlistId = playlistId
  }

  func perform() async throws -> some IntentResult {
    AlarmOpenHandoff.alarmOpened(alarmId: alarmId, playlistId: playlistId)
    return .result()
  }
}

// Found by the AlarmKitBridge pod at runtime via NSClassFromString("${PROVIDER_CLASS_NAME}").
@objc(${PROVIDER_CLASS_NAME})
final class ${PROVIDER_CLASS_NAME}: NSObject {}

@available(iOS 26.0, *)
extension ${PROVIDER_CLASS_NAME}: AlarmOpenIntentProvider {
  static func makeOpenIntent(alarmId: String, playlistId: String?) -> any LiveActivityIntent {
    return OpenSpotifyAlarmIntent(alarmId: alarmId, playlistId: playlistId)
  }
}
`;

/** @type {import('expo/config-plugins').ConfigPlugin<{ usageDescription?: string } | void>} */
const withAlarmKit = (config, props) => {
  const usageDescription = (props && props.usageDescription) || DEFAULT_USAGE;

  config = withInfoPlist(config, (cfg) => {
    cfg.modResults.NSAlarmKitUsageDescription = usageDescription;
    return cfg;
  });

  config = IOSConfig.XcodeProjectFile.withBuildSourceFile(config, {
    filePath: 'SpotifyAlarmOpenIntent.swift',
    contents: intentSource,
    overwrite: true,
  });

  return config;
};

module.exports = withAlarmKit;
